-- Alpha light for the pack shaders (phase 3): the exact light the server sent, not the engine's own.
--
-- VoxelCore computes its own light (no partial opacity: water/ice 3 and leaves 1 in Alpha), and Lua cannot
-- write the engine light map. But Lua can write a region of the "blocks" atlas: assets.to_canvas
-- ("blocks:am_lightmap") -> canvas:set_data + canvas:update() (glTexSubImage2D of the region). The pack's
-- shaders/main.glslf reads it with texelFetch at the face's neighbour cell (RenderBlocks: brightness of the
-- neighbour, World.h[level], level = Chunk.getBlockLightValue = max(sky - World.d, block), World.d = 0 in SMP).
--
-- Region (textures/blocks/am_lightmap.png, generated by tools/alphamine/gen_pack_blocks.py): W = 21*64,
-- H = 21*64 + 2, at atlas texel (2,2) (the tallest texture: LMPacker sorts by height, extrusion 2).
--   rows 0..1343   21x21 chunk slots (slot = cx mod 21, cz mod 21: unique inside the server's +-10 window),
--                  slot = 64x64 texels = 16384 bytes = 32768 nibbles, nibble index = Alpha cell index
--                  x<<11 | z<<7 | y (even index = low nibble), i.e. byte j = the NibbleArray byte j of the
--                  chunk: level byte j = per-nibble max(skylight[j], blocklight[j])
--   cols 1344..2687 the same slots with the cell's fluid code (nibble, same layout): 0 not solid, 1 solid
--                  (Material.isSolid), 2+e water, 10+e/2 lava (e = effective flow decay: meta >= 8 -> 0; lava
--                  decays by 2), 14 ice -- for RenderBlocks.renderBlockFluids (corner heights, flow direction,
--                  BlockFluid.shouldSideBeRendered) in the shaders
--   row 1344       header: texel sz*21+sx = (cx+32768) u16 LE, (cz+32768) u16 LE; 0 = empty slot
--   row 1345       marker texel 0 = "AMLM" (the shader falls back to the engine light without it)
-- Canvas data rows are the atlas texture rows (no flip): byte offset of (col, row) = (row*W + col)*4.
local band, rshift, bor, lshift = bit.band, bit.rshift, bit.bor, bit.lshift
local perf = require "alphamine:perf"

local SLOTS, SLOT = 21, 64
-- side by side, not stacked: LMPacker sorts by height*height*1000 in a 32-bit int (2690 rows overflow it and
-- the region would no longer be placed first)
local W, H = 2 * SLOTS * SLOT, SLOTS * SLOT + 2
local CODES = SLOTS * SLOT              -- first column of the fluid-code map
local HEADER, MARKER = SLOTS * SLOT, SLOTS * SLOT + 1
local META, BLIGHT, SLIGHT = 32768, 49152, 65536
local ID_SLAB, ID_FARMLAND = 44, 60   -- World.getBlockLightValue_do: stairSingle, tilledField

local M = {
    dirty = {},      -- ["cx,cz"] = {cx, cz}
    unsent = {},     -- ["cx,cz"] = true: written into the buffer, not uploaded yet (throttled uploads)
    last_upload = nil,
    owner = {},      -- [slot] = "cx,cz"
    stats = {writes = 0, uploads = 0, ms = 0, special = 0},
    failed = nil,
}

local canvas, buf
local MAXNIB  -- [s*256 + b] = per-nibble max of two nibble bytes
local CODE    -- [id*16 + meta] = fluid code nibble

local function init()
    if canvas or M.failed then return canvas ~= nil end
    local ok, c = pcall(assets.to_canvas, "blocks:am_lightmap")
    if not ok or not c then
        M.failed = "assets.to_canvas(blocks:am_lightmap): " .. tostring(c)
        debug.log("[alphamine] lightmap disabled: " .. M.failed)
        return false
    end
    if c.width ~= W or c.height ~= H then
        M.failed = ("lightmap region %dx%d, expected %dx%d"):format(c.width, c.height, W, H)
        debug.log("[alphamine] lightmap disabled: " .. M.failed)
        return false
    end
    canvas = c
    buf = Bytearray(W * H * 4)
    local p = buf.bytes
    for i = 0, W * H * 4 - 1 do p[i] = 0 end
    local m = MARKER * W * 4
    p[m], p[m + 1], p[m + 2], p[m + 3] = 65, 77, 76, 77   -- "AMLM"
    MAXNIB = {}
    for s = 0, 255 do
        for b = 0, 255 do
            local lo = math.max(band(s, 15), band(b, 15))
            local hi = math.max(rshift(s, 4), rshift(b, 4))
            MAXNIB[s * 256 + b] = bor(lo, lshift(hi, 4))
        end
    end
    CODE = {}
    local T = require "alphamine:blocks_table"
    for id = 0, 255 do
        local e = T[id]
        for meta = 0, 15 do
            local c = 0
            if e then
                local d = meta >= 8 and 0 or meta
                if e.material == "water" then c = 2 + d
                elseif e.material == "lava" then c = 10 + math.floor(d / 2)
                elseif e.material == "ice" then c = 14
                elseif e.solid then c = 1 end
            end
            CODE[id * 16 + meta] = c
        end
    end
    debug.log(("[alphamine] lightmap %dx%d in the blocks atlas"):format(W, H))
    return true
end

local function slot_of(cx, cz)
    return cx % SLOTS, cz % SLOTS   -- Lua % is floored: 0..20 for negatives too
end

local function set_header(sx, sz, cx, cz)
    local o = (HEADER * W + sz * SLOTS + sx) * 4
    local p = buf.bytes
    if cx == nil then
        p[o], p[o + 1], p[o + 2], p[o + 3] = 0, 0, 0, 0
    else
        local a, b = cx + 32768, cz + 32768
        p[o], p[o + 1], p[o + 2], p[o + 3] = band(a, 255), rshift(a, 8), band(b, 255), rshift(b, 8)
    end
end

-- raw level (no stair/farmland rule) of cell i in store s
local function raw_level(s, i)
    local p = s.bytes
    local j = rshift(i, 1)
    local v = MAXNIB[p[SLIGHT + j] * 256 + p[BLIGHT + j]]
    return band(i, 1) == 0 and band(v, 15) or rshift(v, 4)
end

-- level of a neighbour cell by local coords that may leave the chunk (EmptyChunk = 0; y >= 128 -> 15)
local function neighbour_level(stores, cx, cz, s, x, y, z)
    if y >= 128 then return 15 end
    if y < 0 then return 0 end
    if x < 0 or x > 15 or z < 0 or z > 15 then
        local ncx, ncz = cx + math.floor(x / 16), cz + math.floor(z / 16)
        s = stores[ncx .. "," .. ncz]
        if not s then return 0 end
        x, z = x % 16, z % 16
    end
    return raw_level(s, x * 2048 + z * 128 + y)
end

local function write_chunk(cx, cz, s, stores)
    local sx, sz = slot_of(cx, cz)
    local p, sp = buf.bytes, s.bytes
    for ty = 0, SLOT - 1 do
        local o = ((sz * SLOT + ty) * W + sx * SLOT) * 4
        local j0 = ty * 256
        for k = 0, 255 do
            local j = j0 + k
            p[o + k] = MAXNIB[sp[SLIGHT + j] * 256 + sp[BLIGHT + j]]
        end
    end
    -- fluid codes: byte j = cells 2j (low nibble), 2j+1 (high)
    for ty = 0, SLOT - 1 do
        local o = ((sz * SLOT + ty) * W + CODES + sx * SLOT) * 4
        local j0 = ty * 256
        for k = 0, 255 do
            local j = j0 + k
            local mb = sp[META + j]
            local i = j * 2
            p[o + k] = CODE[sp[i] * 16 + band(mb, 15)] + CODE[sp[i + 1] * 16 + rshift(mb, 4)] * 16
        end
    end
    -- stairSingle / tilledField: the cell's own level = max(up, +-x, +-z) (raw values)
    for i = 0, 32767 do
        local id = sp[i]
        if id == ID_SLAB or id == ID_FARMLAND then
            local x, z, y = rshift(i, 11), band(rshift(i, 7), 15), band(i, 127)
            local l = neighbour_level(stores, cx, cz, s, x, y + 1, z)
            l = math.max(l, neighbour_level(stores, cx, cz, s, x + 1, y, z),
                         neighbour_level(stores, cx, cz, s, x - 1, y, z),
                         neighbour_level(stores, cx, cz, s, x, y, z + 1),
                         neighbour_level(stores, cx, cz, s, x, y, z - 1))
            local j = rshift(i, 1)
            local t = rshift(j, 2)
            local o = ((sz * SLOT + rshift(t, 6)) * W + sx * SLOT + band(t, 63)) * 4 + band(j, 3)
            if band(i, 1) == 0 then
                p[o] = bor(band(p[o], 0xF0), l)
            else
                p[o] = bor(band(p[o], 0x0F), lshift(l, 4))
            end
            M.stats.special = M.stats.special + 1
        end
    end
    local slot = sz * SLOTS + sx
    M.owner[slot] = cx .. "," .. cz
    set_header(sx, sz, cx, cz)
    M.stats.writes = M.stats.writes + 1
end

function M.mark(cx, cz)
    local k = cx .. "," .. cz
    if not M.dirty[k] then M.dirty[k] = {cx, cz} end
end

-- stores = chunks.store; chunks without a store are cleared from their slot (if they still own it)
-- min_interval (s, normal launch): the region is uploaded at most once per interval; keys written but not uploaded
-- stay in M.unsent (alphamine:chunks keeps their engine chunks back until then). nil = upload now (F2F).
function M.flush(stores, min_interval)
    if next(M.dirty) == nil and next(M.unsent) == nil then return end
    if not init() then
        M.dirty = {}
        M.unsent = {}
        return
    end
    local t0 = os.clock()
    perf.push("lm_write")
    for k, c in pairs(M.dirty) do
        local s = stores[k]
        if s then
            write_chunk(c[1], c[2], s, stores)
            M.unsent[k] = true
            perf.count("lm_writes")
        else
            local sx, sz = slot_of(c[1], c[2])
            local slot = sz * SLOTS + sx
            if M.owner[slot] == k then
                M.owner[slot] = nil
                set_header(sx, sz, nil)
                M.owner_changed = true   -- the cleared header must reach the GPU (absent chunk = light 0)
            end
        end
    end
    M.dirty = {}
    perf.pop()
    if next(M.unsent) == nil and not M.owner_changed then return end
    local now = perf.clock()
    if min_interval and M.last_upload and now - M.last_upload < min_interval then return end
    M.last_upload = now
    M.unsent = {}
    M.owner_changed = false
    if perf.opts.lm_upload == "off" then return end   -- attribution experiment only
    perf.push("lm_setdata")
    canvas:set_data(buf)
    perf.pop()
    perf.push("lm_upload")
    canvas:update()
    perf.pop()
    perf.count("lm_uploads")
    M.stats.uploads = M.stats.uploads + 1
    M.stats.ms = M.stats.ms + (os.clock() - t0) * 1e3
end

function M.reset()
    M.dirty, M.owner, M.unsent = {}, {}, {}
    if buf then
        local p = buf.bytes
        for slot = 0, SLOTS * SLOTS - 1 do
            local o = (HEADER * W + slot) * 4
            p[o], p[o + 1], p[o + 2], p[o + 3] = 0, 0, 0, 0
        end
        canvas:set_data(buf)
        canvas:update()
    end
end

return M
