#!/usr/bin/env python3
"""AlphaMine phase 3: Alpha 1.0.16 sky/fog constants for the pack shaders -> content/alphamine/shaders/lib/am_sky.glsl

World time in multiplayer is always 0 (WorldClient.tick never calls World.tick), F2F steps use partialTicks 0, so the
sky is a constant picture. Values are computed with Java float semantics (numpy float32, MathHelper's 65536-entry
sine table, Math.cos/Math.pow in double where the Java code does so):
  World.getCelestialAngle(0), getSkyColor, getFogColor, getStarBrightness (0 -> no stars), getCloudColor,
  EntityRenderer.updateFogColor (fog mixed towards the sky by 1 - (1/(4 - renderDistance))^0.25, times the fog
  brightness EntityRenderer.fogColor that converges in float to 0.99999976 after enough ticks),
  RenderGlobal.renderSky: glSkyList2 colour (sky*0.2+0.04, *0.2+0.04, *0.6+0.1), glRotatef(angle*360, 1,0,0).
Textures /terrain/sun.png and /terrain/moon.png (32x32, opaque) are embedded as uint RGB arrays (row 0 = PNG top,
as the GL texture of RenderEngine: v = 0 is the first PNG row).

  python3 tools/alphamine/gen_sky.py
"""
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pngio  # noqa: E402

VC_ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
ALPHA = "/mnt/d/Prog/AlphaMine"
OUT = os.path.join(VC_ROOT, "content", "alphamine", "shaders", "lib", "am_sky.glsl")
f = np.float32
SIN = np.array([math.sin(i * math.pi * 2.0 / 65536.0) for i in range(65536)], dtype=np.float32)


def mcos(x):
    return SIN[int(f(f(x) * f(10430.378)) + f(16384.0)) & 0xffff]


def celestial(time, partial):
    v3 = f(f(f(int(time % 24000)) + f(partial)) / f(24000.0)) - f(0.25)
    v3 = f(v3)
    if v3 < 0:
        v3 = f(v3 + f(1))
    if v3 > 1:
        v3 = f(v3 - f(1))
    v4 = v3
    v3 = f(f(1.0) - f((math.cos(float(v3) * math.pi) + 1.0) / 2.0))
    return f(v4 + f(f(v3 - v4) / f(3.0)))


def clamp01(x):
    return min(max(x, f(0)), f(1))


def sky(time=0, partial=0.0, render_distance=0):
    ang = celestial(time, partial)
    a = f(f(ang * f(math.pi)) * f(2.0))
    b = clamp01(f(f(mcos(a) * f(2.0)) + f(0.5)))
    rgb = lambda c: [f(f(c >> 16 & 255) / f(255.0)), f(f(c >> 8 & 255) / f(255.0)), f(f(c & 255) / f(255.0))]
    skyc = [f(c * b) for c in rgb(0x88BBFF)]
    fr, fg, fb = rgb(0xC0D8FF)
    fogc = [f(fr * f(f(b * f(0.94)) + f(0.06))), f(fg * f(f(b * f(0.94)) + f(0.06))), f(fb * f(f(b * f(0.91)) + f(0.09)))]
    cr, cg, cb = rgb(0xFFFFFF)
    cloud = [f(cr * f(f(b * f(0.9)) + f(0.1))), f(cg * f(f(b * f(0.9)) + f(0.1))), f(cb * f(f(b * f(0.85)) + f(0.15)))]
    v4 = f(f(1.0) / f(4 - render_distance))
    v4 = f(f(1.0) - f(math.pow(float(v4), 0.25)))
    fc = [f(fo + f(f(s - fo) * v4)) for fo, s in zip(fogc, skyc)]
    x = f(0.0)  # EntityRenderer.fogColor: += (1 - fogColor) * 0.1 per tick (render distance FAR -> target 1.0)
    for _ in range(5000):
        x = f(x + f(f(f(1.0) - x) * f(0.1)))
    fc = [f(c * x) for c in fc]
    stars = clamp01(f(f(1.0) - f(f(mcos(a) * f(2.0)) + f(0.75))))
    stars = f(f(stars * stars) * f(0.5))
    sky2 = [f(f(skyc[0] * f(0.2)) + f(0.04)), f(f(skyc[1] * f(0.2)) + f(0.04)), f(f(skyc[2] * f(0.6)) + f(0.1))]
    deg = f(ang * f(360.0))
    return {"angle": ang, "brightness": b, "sky": skyc, "fog": fc, "sky2": sky2, "cloud": cloud, "stars": stars,
            "deg": deg, "fog_brightness": x}


def tex_array(name, path):
    w, h, rows = pngio.read_rgba(open(path, "rb").read())
    vals = []
    for y in range(h):
        r = rows[y]
        for x in range(w):
            vals.append("0x%06Xu" % (r[x * 4] << 16 | r[x * 4 + 1] << 8 | r[x * 4 + 2]))
    lines = ["const uint %s[%d] = uint[](" % (name, w * h)]
    for i in range(0, len(vals), 12):
        lines.append("    " + ", ".join(vals[i:i + 12]) + ("," if i + 12 < len(vals) else ""))
    lines.append(");")
    return w, "\n".join(lines)


def v3(v):
    return "vec3(%s)" % ", ".join(repr(float(x)) for x in v)


def main():
    s = sky()
    d = math.radians(float(s["deg"]))
    ws, sun = tex_array("AM_SUN_TEX", os.path.join(ALPHA, "assets", "terrain", "sun.png"))
    wm, moon = tex_array("AM_MOON_TEX", os.path.join(ALPHA, "assets", "terrain", "moon.png"))
    text = """// GENERATED by tools/alphamine/gen_sky.py -- do not edit. Alpha 1.0.16 sky at world time 0, partialTicks 0.
#ifndef AM_SKY_GLSL_
#define AM_SKY_GLSL_

// World.getCelestialAngle = %r (brightness %r), getStarBrightness = %r (no stars)
const vec3 AM_SKY_COLOR = %s;    // World.getSkyColor
const vec3 AM_FOG_COLOR = %s;    // EntityRenderer.updateFogColor (fog brightness %r)
const vec3 AM_SKY2_COLOR = %s;   // RenderGlobal.renderSky glSkyList2 colour
const vec3 AM_CLOUD_COLOR = %s;  // World.getCloudColor
// glRotatef(angle * 360 = %r deg, 1, 0, 0)
const float AM_CEL_COS = %r;
const float AM_CEL_SIN = %r;
const int AM_SUN_SIZE = %d;
const int AM_MOON_SIZE = %d;
%s
%s

#endif // AM_SKY_GLSL_
""" % (float(s["angle"]), float(s["brightness"]), float(s["stars"]), v3(s["sky"]), v3(s["fog"]), float(s["fog_brightness"]),
       v3(s["sky2"]), v3(s["cloud"]), float(s["deg"]), math.cos(d), math.sin(d), ws, wm, sun, moon)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fo:
        fo.write(text)
    print("%s: angle %.7f sky %s fog %s sky2 %s cloud %s stars %s" % (
        OUT, s["angle"], [round(float(x) * 255, 3) for x in s["sky"]], [round(float(x) * 255, 3) for x in s["fog"]],
        [round(float(x) * 255, 3) for x in s["sky2"]], [round(float(x) * 255, 3) for x in s["cloud"]], s["stars"]))


if __name__ == "__main__":
    main()
