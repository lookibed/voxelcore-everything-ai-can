# ------------------------------------------------------------------------------------------- OBJ writer
class Obj:
    def __init__(self, name, material):
        self.lines = ["# generated by tools/olife/gen_spammer_assets.py (UX B2, olife_b2)", "o %s" % name]
        self.v, self.vt, self.vn, self.f = [], [], [], []
        self.material = material

    def box(self, a, b, uv):
        """axis-aligned box from a to b; uv = (u0, v0, u1, v1) of the texture region for every face"""
        x0, y0, z0 = a
        x1, y1, z1 = b
        c = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0), (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
        faces = [((0, 3, 2, 1), (0, 0, -1)), ((4, 5, 6, 7), (0, 0, 1)), ((0, 1, 5, 4), (0, -1, 0)),
                 ((3, 7, 6, 2), (0, 1, 0)), ((1, 2, 6, 5), (1, 0, 0)), ((0, 4, 7, 3), (-1, 0, 0))]
        u0, v0, u1, v1 = uv
        for idx, n in faces:
            base_v = len(self.v)
            base_t = len(self.vt)
            base_n = len(self.vn)
            for i in idx:
                self.v.append(c[i])
            for t in ((u0, v0), (u1, v0), (u1, v1), (u0, v1)):
                self.vt.append(t)
            self.vn.append(n)
            self.f.append([(base_v + k + 1, base_t + k + 1, base_n + 1) for k in range(4)])

    def sphere(self, r, seg=16, rings=10):
        """UV sphere, equirectangular uv (u = longitude, v = latitude; v 1 = top)"""
        base_v = len(self.v)
        base_t = len(self.vt)
        base_n = len(self.vn)
        for j in range(rings + 1):
            th = math.pi * j / rings
            for i in range(seg + 1):
                ph = 2 * math.pi * i / seg
                x, y, z = r * math.sin(th) * math.cos(ph), r * math.cos(th), r * math.sin(th) * math.sin(ph)
                self.v.append((x, y, z))
                self.vt.append((i / seg, 1 - j / rings))
                self.vn.append((x / r, y / r, z / r))
        for j in range(rings):
            for i in range(seg):
                a = j * (seg + 1) + i
                b = a + seg + 1
                quad = [a, a + 1, b + 1, b]
                self.f.append([(base_v + q + 1, base_t + q + 1, base_n + q + 1) for q in quad])

    def write(self, path):
        out = list(self.lines)
        for x, y, z in self.v:
            out.append("v %.6f %.6f %.6f" % (x, y, z))
        for u, v in self.vt:
            out.append("vt %.6f %.6f" % (u, v))
        for x, y, z in self.vn:
            out.append("vn %.4f %.4f %.4f" % (x, y, z))
        out.append("usemtl %s" % self.material)
        out.append("s off")
        for f in self.f:
            out.append("f " + " ".join("%d/%d/%d" % t for t in f))
        with open(path, "w", newline="\n") as fh:
            fh.write("\n".join(out) + "\n")
        return len(self.v), len(self.f)


