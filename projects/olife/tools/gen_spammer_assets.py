def main():
    os.makedirs(MODELS, exist_ok=True)
    os.makedirs(TEX, exist_ok=True)
    os.makedirs(ICONS, exist_ok=True)
    # palette regions of olife_spammer.png (u0, v0, u1, v1), v up
    METAL = (0.02, 0.77, 0.98, 0.98)
    RED = (0.02, 0.52, 0.98, 0.73)
    WHITE = (0.02, 0.27, 0.98, 0.48)
    GLASS = (0.02, 0.02, 0.48, 0.23)
    BLACK = (0.52, 0.02, 0.98, 0.23)
    g = Obj("olife_spammer", "entities/olife_spammer")
    g.box((-1.20, -0.06, -0.20), (-0.55, 0.08, -0.06), METAL)       # barrel (points -x, as the user's Injector)
    g.box((-1.26, -0.10, -0.24), (-1.18, 0.12, -0.02), BLACK)       # muzzle ring
    g.box((-0.62, -0.02, -0.22), (-0.36, 0.26, -0.04), RED)         # chamber (top half red ...)
    g.box((-0.62, -0.26, -0.22), (-0.36, -0.02, -0.04), WHITE)      # ... bottom half white
    g.box((-0.63, -0.04, -0.23), (-0.35, 0.00, -0.03), BLACK)       # the band
    g.box((-0.55, 0.26, -0.17), (-0.43, 0.30, -0.09), GLASS)        # indicator window
    g.box((-0.92, -0.30, -0.18), (-0.78, -0.06, -0.08), METAL)      # grip
    g.box((-1.02, 0.08, -0.16), (-0.86, 0.14, -0.10), GLASS)        # sight
    nv, nf = g.write(os.path.join(MODELS, "olife_spammer.obj"))
    print("olife_spammer.obj", nv, "vertices", nf, "faces")
    b = Obj("olife_spamball", "entities/olife_spamball")
    b.sphere(0.28, 16, 10)
    nv, nf = b.write(os.path.join(MODELS, "olife_spamball.obj"))
    print("olife_spamball.obj", nv, "vertices", nf, "faces")
    tex_spammer(os.path.join(TEX, "olife_spammer.png"))
    tex_ball(os.path.join(TEX, "olife_spamball.png"))
