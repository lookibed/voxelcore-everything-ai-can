"""UX B2 (03.10, olife_b2): models, textures and the icon of the Spammer tool and its ball (content/olife_client).
The user's prototype (0.30.6 Olife / GravityGun packs, 0.31.0_pre2 content) has no spammer / ball model, so these are
generated in the same technical form as the imported ones: OBJ with `usemtl entities/<name>` (0.32 reads OBJ without
.mtl, the material name = texture), the in-hand gun sits where the user's Injector sits (x -1.2..-0.35, pointing -x).
Deterministic; run again after editing.

  python3 tools/olife/gen_spammer_assets.py
"""
