class Bucket:
    def __init__(self, rate, burst):
        self.rate, self.burst, self.v, self.t = rate, burst, burst, time.monotonic()

    def take(self, n=1.0):
        t = time.monotonic()
        self.v = min(self.burst, self.v + (t - self.t) * self.rate)
        self.t = t
        if self.v < n:
            return False
        self.v -= n
        return True


