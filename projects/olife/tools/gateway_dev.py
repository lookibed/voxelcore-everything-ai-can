    # ------------------------------------------------------------------ world link
    def world_send(self, name, msg):
        fr = I.frame(name, msg)
        with self.up_lock:
            if self.up is None:
                return False
            try:
                self.up.sendall(fr)
            except OSError:
                return False
        with self.lock:
            self.m["world_bytes_out"] += len(fr)
        return True

    def world_loop(self):
        host, port = self.a["upstream"].rsplit(":", 1)
        while True:
            try:
                s = socket.create_connection((host, int(port)), timeout=5)
            except OSError as exc:
                self.world["state"] = "connect failed: %s" % exc
                time.sleep(1.0)
                continue
            s.settimeout(None)
            s.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
            with self.up_lock:
                self.up = s
            self.m["world_connects"] += 1
            self.world_send("GatewayHello", {"proto": I.VERSION, "gateway": self.name, "secret": self.secret,
                                             "client_proto": C.VERSION})
            fr = I.framer()
            why = "closed"
            try:
                while True:
                    data = s.recv(262144)
                    if not data:
                        break
                    with self.lock:
                        self.m["world_bytes_in"] += len(data)
                    fr.feed(data)
                    while True:
                        x = fr.next()
                        if x is None:
                            break
                        self.on_world(*x)
            except (OSError, ProtoError) as exc:
                why = "%s: %s" % (type(exc).__name__, exc)
            with self.up_lock:
                self.up = None
            self.world_ready.clear()
            self.world["state"] = "lost: " + why
            self.event("world_lost", why=why, supervised=self.supervised)
            # the client contract has no "world restarting, hold on" message: sessions are closed with a reason;
            # supervised clients (--reconnect) come back when the world is up again
            reason = ("world restarting (supervisor%s): reconnect" % (", " + self.world_note if self.world_note else "")
                      if self.supervised else "world connection lost")
            for c in list(self.sessions.values()):
                c.disconnect("world_unavailable", reason)
            try:
                s.close()
            except OSError:
                pass
            time.sleep(1.0)

    def on_world(self, mid, body):
        m = I.decode_body(mid, body)
        name = I.NAMES[mid]
        if name == "WorldHello":
            self.world = dict(m, state="ready")
            self.world_ready.set()
            self.world_note = None
            self.event("world_ready", world=m["world"], tick=m["tick"])
        elif name == "Data":
            c = self.sessions.get(m["session"])
            if c:
                c.deliver(m["type"], m["payload"])
        elif name == "Multicast":
            for sid in m["sessions"]:
                c = self.sessions.get(sid)
                if c:
                    c.deliver(m["type"], m["payload"])
        elif name == "Detach":
            c = self.sessions.get(m["session"])
            if c:
                c.disconnect("kicked", m["reason"], code=m["code"] or CODES["kicked"], notify_world=False)
        elif name == "Ping":
            self.world_send("Pong", {"seq": m["seq"], "ms": m["ms"]})

